"""Build single-file versions of the EA and scripts (EA/standalone/*.mq5) by inlining the
ClaudeEA include modules. A standalone file needs nothing copied into MQL5/Include: drop it
into MQL5/Experts (or MQL5/Scripts) and compile. Standard-library includes are kept.

    python tools_mql_bundle.py          # rewrite EA/standalone
    python tools_mql_bundle.py --check  # exit 1 if EA/standalone is out of date
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "EA")
INC = os.path.join(ROOT, "Include", "ClaudeEA")
OUT = os.path.join(ROOT, "standalone")
TARGETS = {
    "Claude_AI_MT5.mq5": os.path.join(ROOT, "Claude_AI_MT5.mq5"),
    "ClaudeEA_SelfTest.mq5": os.path.join(ROOT, "Scripts", "ClaudeEA_SelfTest.mq5"),
    "ClaudeEA_ExportBars.mq5": os.path.join(ROOT, "Scripts", "ClaudeEA_ExportBars.mq5"),
}
OWN = re.compile(r'^\s*#include\s+(?:<ClaudeEA\\([\w.]+)>|"([\w.]+)")\s*$')
GUARD = re.compile(r"^\s*#(ifndef|define|endif)\b.*CLAUDEEA_\w+_MQH")


def inline(path: str, done: set) -> list:
    out = []
    for line in open(path, encoding="utf-8").read().splitlines():
        m = OWN.match(line)
        if m:
            name = m.group(1) or m.group(2)
            if name not in done:
                done.add(name)
                out.append(f"//==================== begin {name} ====================")
                out += inline(os.path.join(INC, name), done)
                out.append(f"//==================== end {name} ====================")
            continue
        if GUARD.match(line):
            continue
        out.append(line)
    return out


def build(src: str) -> str:
    head = ["// STANDALONE BUILD - generated by tools_mql_bundle.py from the modular sources.",
            "// Do not edit here; edit EA/Include/ClaudeEA/*.mqh and regenerate.", ""]
    return "\n".join(head + inline(src, set())) + "\n"


def main() -> int:
    check, stale = "--check" in sys.argv, []
    os.makedirs(OUT, exist_ok=True)
    for name, src in TARGETS.items():
        text, dst = build(src), os.path.join(OUT, name)
        if check:
            if not os.path.exists(dst) or open(dst, encoding="utf-8").read() != text:
                stale.append(name)
        else:
            with open(dst, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
            print(f"wrote {os.path.relpath(dst, ROOT)} ({text.count(chr(10))} lines)")
    if stale:
        print("out of date: " + ", ".join(stale))
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
